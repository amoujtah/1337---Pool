int	ft_sqrt(int nb)
{
	int	i;
	int	trouve;

	trouve = 0;
	i = 0;
	if (nb <= 0)
	{
		return (0);
	}
	if (nb == 1)
	{
		return (1);
	}
	while (i <= nb)
	{
		if (i * i == nb)
		{
			trouve = i;
			break ;
		}
		i++;
	}
	return (trouve);
}

int	ft_iterative_factorial(int nb)
{
	int	i;
	int	s;

	s = 1;
	i = 1;
	if (nb < 0)
	{
		return (0);
	}
	while (i <= nb)
	{
		s = s * i;
		i++;
	}
	return (s);
}

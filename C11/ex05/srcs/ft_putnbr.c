#include "ft.h"

void	ft_putnbr(int nb)
{
	if (nb == -2147483648)
	{
		write(1, "-2147483648", 11);
	}
	else if (nb < 0)
	{
		ft_putchar ('-');
		nb = -nb;
		ft_putnbr (nb);
	}
	else if (nb >= 10)
	{
		ft_putnbr (nb / 10);
		ft_putchar ((nb % 10) + '0');
	}
	else
	{
		ft_putchar (nb + '0');
	}
}
